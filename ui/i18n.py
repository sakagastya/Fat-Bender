STRINGS = {"en": EN, "id": ID}


def current_lang():
    return st.session_state.get("app_language", "en")


def tr(key, **kwargs):
    table = STRINGS.get(current_lang(), STRINGS["en"])
    template = table.get(key) or STRINGS["en"][key]
    return template.format(**kwargs) if kwargs else template


def goal_choices():
    lang = STRINGS.get(current_lang(), STRINGS["en"])
    return [(lang["goal_cut"], "cut"), (lang["goal_bulk"], "bulk")]


def sex_choices():
    lang = STRINGS.get(current_lang(), STRINGS["en"])
    return [(lang["sex_male"], "male"), (lang["sex_female"], "female")]


def language_selector():
    lang = STRINGS.get(current_lang(), STRINGS["en"])
    labels = [label for label, _ in LANG_CHOICES]
    codes = dict(LANG_CHOICES)
    picked = st.selectbox(
        lang["language_label"], labels,
        index=1 if current_lang() == "id" else 0,
        key="lang_pick", label_visibility="collapsed",
    )
    st.session_state.app_language = codes[picked]
